import { readFileSync, writeFileSync } from "node:fs";

// Bake the AUDB plaintext byte-frequency model used by the key recovery
// attack. Source: the bundled donor (plaintext AUDB) plus a decoded
// device save, so the model describes the format rather than one account.
const sources = ["data/gardens-account.db", `${process.env.TEMP}\\gs-test\\stats.db`];
const XOR_KEY_PATH = "src/lib/gardenscapes/key.ts";
const xorKeySrc = readFileSync(XOR_KEY_PATH, "utf8");
const m = xorSrcMatch(xorKeySrc);
function xorSrcMatch(s: string): string {
  const hit = /export const XOR_KEY = "((?:[^"\\]|\\.)*)"/.exec(s);
  if (!hit) throw new Error("XOR_KEY not found");
  return JSON.parse(`"${hit[1]}"`);
}
const K = Uint8Array.from(m, (c) => c.charCodeAt(0));

const cnt = new Float64Array(256);
let total = 0;
for (const p of sources) {
  const raw = readFileSync(p);
  const plain = new Uint8Array(raw.length);
  const isPlain = raw[0] === 0x41 && raw[1] === 0x55 && raw[2] === 0x44 && raw[3] === 0x42;
  if (isPlain) plain.set(raw);
  else for (let i = 0; i < raw.length; i++) plain[i] = raw[i] ^ K[i % 731];
  for (const b of plain) cnt[b]++;
  total += plain.length;
  console.log(`${p}: ${raw.length}B plain=${isPlain}`);
}
const logp: number[] = [];
for (let b = 0; b < 256; b++) logp.push(Number((Math.log((cnt[b] + 0.5) / (total + 128))).toFixed(6)));
console.log(`total plaintext bytes: ${total}`);

const rows: string[] = [];
for (let i = 0; i < 256; i += 8) rows.push("  " + logp.slice(i, i + 8).join(", ") + ",");
const out = `/**
 * Byte-frequency log-model of a Gardenscapes AUDB plaintext document, used by
 * the known-plaintext key recovery in ./key-recover.ts.
 *
 * Built from the bundled donor (data/gardens-account.db, plaintext AUDB) and a
 * decoded device save, so it describes the AUDB format rather than one
 * account. Values are ln P(byte) with additive smoothing.
 *
 * Generated by scripts/bake-key-model.ts. Do not hand-edit.
 */
export const AUDB_BYTE_LOGP: readonly number[] = [
${rows.join("\n")}
];
`;
writeFileSync("src/lib/gardenscapes/key-model.ts", out);
console.log("wrote src/lib/gardenscapes/key-model.ts");
